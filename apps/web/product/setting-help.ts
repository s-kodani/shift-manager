export function settingHelp(title: string): string | undefined {
  if (explanations[title]) return explanations[title];
  if (/^段階 \d+ の番号$/.test(title)) return '習熟度の順序を表す番号です。数字が大きいほど高い段階になります。同じ番号は重複して登録できません。';
  if (/^段階 \d+ の名称$/.test(title)) return 'この習熟度の分かりやすい名前です。たとえば「初心者」「一人で対応できる」「熟練者」のように入力します。';
  if (/ の能力係数$/.test(title)) return 'この段階のスタッフ1人が処理できる量を、標準の何人分かで入力します。1なら1人分、0.5なら半人分です。業務を担当できるかどうかの最低習熟度とは別の設定です。';
  if (/（最低習熟度 .+）$/.test(title)) return explanations['業務ごとの習熟度'];
  if (/ → .+（分）$/.test(title)) return '左の業務から右の業務へ移るときに、準備や移動にかかる分数です。逆方向とは別に設定します。不要なら0、必要な場合は業務配置1枠以内の整数分で入力します。';
  const item = title.replace(/^(需要|予定|担当区分の条件) \d+ /, '');
  if (item !== title) {
    if (item === '日付') return 'この人数・予定・担当区分の条件を適用する日を選びます。対象月の中の日付を指定します。';
    if (item === '開始' || item === '終了') return 'この人数・予定・担当区分の条件を適用する時間帯です。開始より終了を後にし、コロンなしの数字4桁のHHMM（例：0930）で入力します。需要・担当区分の条件は業務配置枠に合わせます。';
    if (item === '業務') return 'この時間帯に必要人数を設定する一般業務を選びます。';
    if (item.startsWith('直接必要人数')) return '標準の何人分の処理能力が必要かを入力します。直接入力は算出値より優先されます。0は「必要なし」、空欄は「未設定」なので区別してください。';
    if (item === '種別') return '研修か会議かを選びます。どちらも、参加者が予定の全時間に参加できる勤務が必要です。';
    if (item === '対象範囲') return 'チーム全体の一般業務で人数を数えるか、選んだ業務だけで数えるかを指定します。';
    if (item === '担当区分') return 'この時間帯に必要なSV・リーダーなどの担当区分を選びます。スタッフの「対応可能な担当」に登録され、実際にその担当区分で一般業務を処理している人を数えます。';
    if (item === '最低人数') return 'この時間帯に少なくとも必要な、その担当区分の人数です。比率でも人数を求める場合は、大きい方を採用します。';
    if (item === '比率の分子' || item === '比率の分母') return '一般業務の人数に対して必要な担当区分の割合です。たとえば分子1・分母5は5人につき1人です。比率を使わない場合は分子0・分母1にします。一般業務を兼ねているSV・リーダーは分母から除きます。';
    if (item === 'の参加者') return 'この研修・会議に参加するスタッフを選びます。全時間参加できる必要があるため、勤務や休憩と重ならないか確認します。';
  }
  if (/^担当区分の区間\d+の(開始|終了)$/.test(title)) return 'SV・リーダーなどを担当する時間帯です。実際に一般業務を処理する時間の中に設定します。';
  if (/^担当区分の区間\d+の担当区分$/.test(title)) return 'この時間帯の担当区分を選びます。スタッフ設定の「対応可能な担当」の範囲で設定します。';
  return undefined;
}
