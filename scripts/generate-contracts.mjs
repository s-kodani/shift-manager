import { readFileSync, writeFileSync } from 'node:fs';

// Build-time translation of the JSON Schema subset used by this repository.
// Unsupported validation keywords fail generation instead of disappearing.
const schema = JSON.parse(readFileSync('packages/contracts/optimizer-multi-task.schema.json', 'utf8'));
const known = new Set(['$schema','$id','$ref','$defs','title','type','const','enum','oneOf','additionalProperties','required','properties','items','minItems','maxItems','uniqueItems','minLength','maxLength','pattern','format','minimum','maximum','multipleOf']);
function emit(s) {
  for (const key of Object.keys(s)) if (!known.has(key)) throw new Error(`Unsupported schema keyword: ${key}`);
  for (const branch of ['$ref','const','enum','oneOf']) if (branch in s && Object.keys(s).some(key => key !== branch && !['$schema','$id','$defs','title'].includes(key))) {
    throw new Error(`Validation siblings of ${branch} are unsupported`);
  }
  if (s.$ref) {
    if (!s.$ref.startsWith('#/$defs/')) throw new Error('External refs are unsupported');
    return emit(schema.$defs[s.$ref.slice('#/$defs/'.length)]);
  }
  if ('const' in s) return `z.literal(${JSON.stringify(s.const)})`;
  if (s.enum) return `z.union([${s.enum.map(v=>`z.literal(${JSON.stringify(v)})`).join(',')}])`;
  if (s.oneOf) {
    const types = s.oneOf.map(branch => {
      const resolved = branch.$ref ? schema.$defs[branch.$ref.slice('#/$defs/'.length)] : branch;
      if (typeof resolved.type !== 'string') throw new Error('oneOf requires disjoint primitive types');
      return resolved.type;
    });
    if (new Set(types).size !== types.length) throw new Error('Overlapping oneOf branches are unsupported');
    return `z.union([${s.oneOf.map(emit).join(',')}])`;
  }
  if (Array.isArray(s.type)) return `z.union([${s.type.map(type=>emit({...s,type})).join(',')}])`;
  let result;
  if (s.type === 'null') return 'z.null()';
  if (s.type === 'object') {
    if (s.additionalProperties !== false) throw new Error('Only strict object contracts are supported');
    result=`z.object({${Object.entries(s.properties).map(([key,value])=>`${JSON.stringify(key)}:${emit(value)}${s.required?.includes(key)?'':'.optional()'}`).join(',')}}).strict()`;
  } else if (s.type === 'array') {
    result=`z.array(${emit(s.items)})`;
    if (s.minItems !== undefined) result+=`.min(${s.minItems})`;
    if (s.maxItems !== undefined) result+=`.max(${s.maxItems})`;
    if (s.uniqueItems) result+='.refine((items) => new Set(items.map((item) => JSON.stringify(item))).size === items.length, "DUPLICATE_ITEMS")';
  } else if (s.type === 'string') {
    result='z.string()';
    if (s.minLength !== undefined) result+=`.refine((value) => [...value].length >= ${s.minLength}, "STRING_TOO_SHORT")`;
    if (s.maxLength !== undefined) result+=`.refine((value) => [...value].length <= ${s.maxLength}, "STRING_TOO_LONG")`;
    if (s.pattern) result+=`.regex(new RegExp(${JSON.stringify(s.pattern)}))`;
    if (s.format) {
      if (s.format !== 'date') throw new Error('Unsupported format');
      result+='.refine(validDate, "INVALID_DATE")';
    }
  } else if (s.type === 'integer') {
    result='z.number().int()';
    if (s.minimum !== undefined) result+=`.min(${s.minimum})`;
    if (s.maximum !== undefined) result+=`.max(${s.maximum})`;
    if (s.multipleOf !== undefined) result+=`.multipleOf(${s.multipleOf})`;
  } else throw new Error(`Unsupported schema type: ${s.type}`);
  return result;
}
const content=`// Generated by scripts/generate-contracts.mjs; edit the JSON Schema instead.\nimport { z } from 'zod';\nfunction validDate(value: string) {\n  if (!/^\\d{4}-\\d{2}-\\d{2}$/.test(value)) return false;\n  const [year,month,day] = value.split('-').map(Number);\n  const leap = year % 4 === 0 && (year % 100 !== 0 || year % 400 === 0);\n  const days = [31,leap?29:28,31,30,31,30,31,31,30,31,30,31];\n  return year > 0 && month >= 1 && month <= 12 && day >= 1 && day <= days[month-1];\n}\nexport const optimizerInputSchema = ${emit(schema)};\nexport type OptimizerInput = z.infer<typeof optimizerInputSchema>;\nexport const optimizerAssignmentsSchema = ${emit({type:'array',items:{$ref:'#/$defs/assignment'}})};\nexport type OptimizerAssignments = z.infer<typeof optimizerAssignmentsSchema>;\n`;
const target='packages/contracts/optimizer-input.generated.ts';
if (process.argv.includes('--check')) {
  if (readFileSync(target,'utf8')!==content) throw new Error('Generated contracts are stale: npm run contracts:generate');
} else writeFileSync(target,content);
